/**
 * 원문 언어 추정 (2026-08-20 — 실측으로 잡은 조용한 오작동).
 *
 * 🔴 **왜 생겼나.** 예전 추정은 `refineClient.js` 안에 한 줄이었다:
 *
 *      /[가-힣]/.test(text) ? 'ko' : 'en'
 *
 *    한글이 아니면 **무조건 영어**다. 그래서 일본어·중국어·독일어 메시지를 뜻 풀기에 넣으면
 *    `sourceLanguage: 'en'`으로 **위장돼 검증을 통과**했다. 400도 안 나고 화면도 멀쩡한데,
 *    모델에게는 "이건 영어다"라고 말한 채 해독을 시키는 상태였다 — **조용히 틀리는 쪽**이라
 *    사용자가 알아챌 방법이 없었다.
 *
 * 🔴 **문자(script)로만 판정한다.** 낱말 사전이나 통계 모델을 쓰지 않는다 — 확장 번들에
 *    사전을 싣는 비용이 크고, 짧은 업무 메시지에서는 오히려 흔들린다. 문자는 짧아도 확실하다.
 *
 * 🔴 **판정표 — 위에서부터 처음 맞는 행을 쓴다. 표에 없는 경우를 임의로 처리하지 않는다.**
 *
 * | # | 조건 | 판정 | 근거 |
 * |---|---|---|---|
 * | 1 | 한글(가-힣·ㄱ-ㅎ·ㅏ-ㅣ)이 있다 | `ko` | 한글은 한국어에서만 쓴다 |
 * | 2 | 가나(히라가나·가타카나)가 있다 | `ja` | **한자보다 먼저 본다** — 일본어는 한자와 가나를 섞어 쓰므로, 한자를 먼저 보면 전부 중국어가 된다 |
 * | 3 | 한자(CJK 통합 한자)가 있다 | `zh` | 가나도 한글도 없는 한자문 |
 * | 4 | 키릴 문자가 있다 | `en` | 🔴 러시아어는 **지원 목록에 없다.** 지어내지 않고 기본값으로 보낸다 |
 * | 5 | 그 밖 | `en` | 라틴 문자권(en·de·fr·es)은 문자로 못 가른다 — 아래 주석 참고 |
 *
 * 🔴 **라틴 문자권을 문자로 가르지 않는 이유.** 독일어·프랑스어·스페인어는 영어와 같은 문자를
 *    쓴다. `ä`·`ç`·`ñ` 같은 글자로 찍으려 해 봤자 **그 글자가 없는 문장이 대부분**이고
 *    (`Bitte prüfen Sie das`에는 있지만 `Danke fur alles`에는 없다), 틀리면 4번 행과 같은
 *    「조용히 틀리는」 실패로 돌아간다. 그래서 **영어로 두고, 사용자가 고를 수 있게 하는 것이
 *    맞는 해법**이다(수신자 언어 설정·온보딩 내 언어).
 *
 * 🔴 이 함수는 **추정일 뿐**이며, 호출부가 명시한 값이 있으면 그쪽이 언제나 이긴다.
 */

/** 지원 언어 — `core/refine/index.js`·`core/decode/index.js`의 목록과 같아야 한다. */
export const DETECTABLE_LANGUAGES = ['ko', 'ja', 'zh', 'en'];

const HANGUL = /[가-힣ㄱ-ㅎㅏ-ㅣ]/;
/** 히라가나 + 가타카나 (반각 가타카나 포함). */
const KANA = /[぀-ゟ゠-ヿｦ-ﾝ]/;
/** CJK 통합 한자 (확장 A 포함). */
const HAN = /[㐀-䶿一-鿿]/;

/**
 * @param {string} text 원문.
 * @returns {'ko'|'ja'|'zh'|'en'} 판정표대로. 빈 값이면 `en`.
 */
export function detectLanguage(text) {
  const value = String(text ?? '');
  if (HANGUL.test(value)) return 'ko';
  // 🔴 가나가 한자보다 먼저다 — 순서를 바꾸면 일본어가 전부 중국어로 판정된다.
  if (KANA.test(value)) return 'ja';
  if (HAN.test(value)) return 'zh';
  return 'en';
}
